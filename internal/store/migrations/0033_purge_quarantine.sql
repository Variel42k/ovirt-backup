-- Карантин удаления копий.
--
-- Удаление копии до сих пор стирало данные немедленно. Это и есть основной
-- сценарий атаки шифровальщиком: сначала уничтожают копии, потом шифруют
-- инфраструктуру, — и от захвата учётной записи администратора до потери
-- истории проходили секунды.
--
-- Теперь удаление помечает копию и назначает срок. Данные лежат нетронутыми,
-- пока он не вышел: за это время ошибку замечают, а злоумышленника — тем
-- более, потому что удаление попадает и в журнал аудита, и в оповещения.
--
-- purge_after заполнен — копия в карантине: помечена удалённой, но данные на
-- месте и её можно вернуть. Пусто — либо копия жива, либо данные уже стёрты;
-- различает эти два случая колонка deleted, которая была и раньше.
ALTER TABLE backup_runs
    ADD COLUMN IF NOT EXISTS purge_after TIMESTAMPTZ;

-- Сборщик перебирает только те, чей срок вышел.
CREATE INDEX IF NOT EXISTS idx_backup_runs_purge_due
    ON backup_runs(purge_after)
    WHERE purge_after IS NOT NULL;
