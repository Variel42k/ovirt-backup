-- Аренда задачи репликации: кто её взял.
--
-- Колонка locked_until в схеме была с самого начала, но не использовалась:
-- worker-ы разбирали очередь обычным SELECT, а от того, чтобы двое взяли одну
-- задачу, спасала карта в памяти процесса. Внутри одного процесса это
-- работает, между процессами — нет, и второй экземпляр службы начал бы
-- переливать те же гигабайты второй раз.
--
-- Кто держит аренду, нужно знать по двум причинам: продлевать её вправе только
-- владелец, а в интерфейсе видно, чья задача повисла.

ALTER TABLE backup_copies ADD COLUMN IF NOT EXISTS locked_by TEXT NOT NULL DEFAULT '';

-- Выборка задач идёт по роли, обязательности, статусу и сроку следующей
-- попытки. На десятках тысяч копий последовательный просмотр начинает
-- обходиться дороже самой передачи.
CREATE INDEX IF NOT EXISTS backup_copies_due_idx
    ON backup_copies (status, next_retry_at)
    WHERE role = 'replica' AND required;

COMMENT ON COLUMN backup_copies.locked_by IS 'идентификатор worker-а, держащего аренду; пусто — задача свободна';
