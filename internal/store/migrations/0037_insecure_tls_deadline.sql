-- Отключённая проверка сертификата перестаёт быть бессрочной.
--
-- Галку «не проверять сертификат» ставят на полчаса, чтобы подключиться сегодня,
-- а снимают никогда: напоминать о ней некому, в интерфейсе она выглядит как
-- обычная настройка, и через год никто уже не помнит, что движок опрашивается
-- без проверки подлинности.
--
-- Отметка времени превращает её во временный режим: интерфейс показывает, сколько
-- он длится, а служба поднимает оповещение, когда срок вышел.
ALTER TABLE servers
    ADD COLUMN IF NOT EXISTS insecure_tls_since TIMESTAMPTZ;

ALTER TABLE storage_targets
    ADD COLUMN IF NOT EXISTS insecure_tls_since TIMESTAMPTZ;

-- Уже включённым режимам отсчёт начинается с обновления.
--
-- Когда галку поставили на самом деле, неизвестно: до этой миграции время не
-- записывалось. Начинать отсчёт заново честнее, чем выдумывать дату, и это даёт
-- оператору полный срок на то, чтобы разобраться, а не оповещение сразу после
-- обновления.
UPDATE servers
   SET insecure_tls_since = NOW()
 WHERE insecure_tls AND insecure_tls_since IS NULL;

UPDATE storage_targets
   SET insecure_tls_since = NOW()
 WHERE insecure_tls AND insecure_tls_since IS NULL;
