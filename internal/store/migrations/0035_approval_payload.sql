-- Параметры действия и причина неудачи автоматического выполнения.
--
-- Уровень veto выполняет действие сам, когда окно отмены вышло, и человека,
-- который повторил бы запрос, рядом нет. Для удаления хватает object_id, а
-- применению политики хранения нужны ещё сервер, ВМ, хранилище и сама
-- политика — они и лежат здесь.
--
-- Секретам здесь не место: заявка живёт в базе и уходит в оповещения, то есть
-- всё, что сюда попало, оказывается сразу в двух местах, откуда это не
-- отозвать. Действия, которым для повтора нужен секрет, автоматически не
-- выполняются — их доводит человек.
ALTER TABLE approval_requests
    ADD COLUMN IF NOT EXISTS payload BYTEA;

-- Почему автоматическое выполнение не удалось.
--
-- Заявка при этом не закрывается: молча пропавшее действие, которое все
-- считают выполненным, хуже отказа.
ALTER TABLE approval_requests
    ADD COLUMN IF NOT EXISTS error TEXT NOT NULL DEFAULT '';
