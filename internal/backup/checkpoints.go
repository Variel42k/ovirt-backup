package backup

// Ротация checkpoint-ов.
//
// Каждый горячий бэкап с отслеживанием изменённых блоков оставляет на
// гипервизоре checkpoint — точку, от которой считается следующий инкремент.
// Сами они не исчезают: в libvirt их битмапы копятся в заголовке qcow2, в
// oVirt — в базе движка, и движок пересоздаёт их на хосте при каждом старте
// ВМ. Нужны же из них единицы: те, от которых ещё может считаться следующий
// бэкап.
//
// Удаляются только свои checkpoint-ы и только те, что основой уже не станут.
// Ошибиться здесь недорого: если удалённый checkpoint всё-таки понадобится,
// следующий бэкап увидит, что его нет, и честно сделает полную копию.

// CheckpointsToDrop выбирает checkpoint-ы, которые можно удалить.
//
// chain — checkpoint-ы ВМ от старого к новому, как их отдаёт гипервизор.
// ours сообщает, создала ли checkpoint служба: чужие не трогаются никогда —
// ими может пользоваться другая система копирования. keep — те, от которых
// ещё может считаться бэкап.
//
// rootOnly — гипервизор удаляет только самый старый checkpoint (oVirt):
// удаление идёт с корня и останавливается на первом, который трогать нельзя.
// Иначе (libvirt) удаляются все подходящие: libvirt сливает битмап удалённого
// checkpoint-а с соседним, и остальные остаются пригодными.
//
// Самый новый checkpoint не удаляется ни при каком раскладе: это точка только
// что завершённого бэкапа, даже если каталог ещё не успел её записать. Пустой
// keep означает, что неизвестно, что нужно, — тогда не удаляется ничего.
func CheckpointsToDrop(chain []string, ours func(string) bool, keep map[string]bool, rootOnly bool) []string {
	if len(chain) < 2 || len(keep) == 0 {
		return nil
	}
	candidates := chain[:len(chain)-1]
	var drop []string
	for _, id := range candidates {
		removable := id != "" && ours(id) && !keep[id]
		if !removable {
			if rootOnly {
				break
			}
			continue
		}
		drop = append(drop, id)
	}
	return drop
}
