-- Внешние учётные записи: вход через OIDC-провайдера рядом с локальным.
--
-- Пароль у такой записи не задаётся вовсе: его проверяет провайдер, и хранить
-- здесь нечего. Поэтому password_hash становится необязательным, а вход по
-- паролю разрешён только записям, у которых он есть.
--
-- Локальные учётные записи остаются: это система восстановления, и к ней идут
-- тогда, когда инфраструктура уже сломана. Если единственный путь входа лежит
-- через провайдера, а провайдер живёт на той самой ВМ, которую восстанавливают,
-- консоль восстановления недоступна ровно в тот момент, когда она нужна.

ALTER TABLE users ADD COLUMN IF NOT EXISTS provider TEXT NOT NULL DEFAULT 'local';
ALTER TABLE users ADD COLUMN IF NOT EXISTS external_id TEXT NOT NULL DEFAULT '';
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;

-- Пара «провайдер + идентификатор у провайдера» уникальна, но только для
-- внешних записей: у локальных external_id пуст, и они попали бы в конфликт
-- друг с другом. Частичный индекс отсекает их условием.
CREATE UNIQUE INDEX IF NOT EXISTS users_provider_external_id_idx
    ON users (provider, external_id)
    WHERE external_id <> '';

-- Идентификатор у провайдера (sub) неизменен, а имя пользователя и почта — нет.
-- Связь ведётся по нему, поэтому переименование в каталоге не создаёт вторую
-- учётную запись и не теряет прав.
COMMENT ON COLUMN users.external_id IS 'sub от провайдера; пусто у локальных записей';
COMMENT ON COLUMN users.provider IS 'local либо имя внешнего провайдера';
