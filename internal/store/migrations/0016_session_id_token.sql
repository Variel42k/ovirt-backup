-- Выход через провайдера: RP-Initiated Logout.
--
-- Провайдеру при выходе нужен id_token_hint — тот самый токен, по которому мы
-- заводили сессию. Без него Keycloak и остальные показывают страницу «точно
-- выйти?», а часть провайдеров просто отказывает.
--
-- Токен лежит рядом с самой сессией и живёт ровно столько же: это такой же
-- ключ от входа, как и token в этой строке, и защищён он теми же правами на
-- таблицу. Хранить его дольше сессии смысла нет — при удалении строки он
-- уходит вместе с ней.
--
-- Пусто у локальных входов: там выходить не у кого.

ALTER TABLE sessions ADD COLUMN IF NOT EXISTS oidc_id_token TEXT;

COMMENT ON COLUMN sessions.oidc_id_token IS 'id_token провайдера для выхода; пусто у входов по паролю';
