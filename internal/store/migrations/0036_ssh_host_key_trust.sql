-- Отказ от проверки ключа SSH-хоста становится явным.
--
-- Раньше пустой ключ хоста означал «подключаться без проверки»: и у
-- гипервизоров, и у SFTP-хранилищ. Это тот отказ, которого никто не замечает —
-- перехваченное соединение выглядит ровно как работающее, а через подключение к
-- гипервизору проходят диски всех его виртуальных машин.
--
-- Теперь пустой ключ означает «ключ ещё не задан», и подключения не будет.
-- Отказаться от проверки можно, но отдельным признаком: он виден в интерфейсе и
-- записывается в журнал аудита.
--
-- Значение по умолчанию для НОВЫХ записей — FALSE, то есть проверять.
ALTER TABLE servers
    ADD COLUMN IF NOT EXISTS ssh_trust_any_host_key BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE storage_targets
    ADD COLUMN IF NOT EXISTS trust_any_host_key BOOLEAN NOT NULL DEFAULT FALSE;

-- Уже заведённые подключения без ключа переводятся в явное «без проверки».
--
-- Не ужесточение задним числом: до этой миграции они работали именно так, и
-- обновление службы не должно ночью остановить резервное копирование. Разница в
-- том, что прежде это состояние было невидимым, а теперь оно записано, показано
-- оператору и может быть снято по одному подключению за раз.
--
-- Условие по ssh_host_key важно: подключения, где ключ УЖЕ задан, остаются
-- проверяемыми. Ослаблять их было бы настоящим ужесточением наоборот.
UPDATE servers
   SET ssh_trust_any_host_key = TRUE
 WHERE kind = 'kvm'
   AND COALESCE(TRIM(ssh_host_key), '') = '';

UPDATE storage_targets
   SET trust_any_host_key = TRUE
 WHERE kind = 'sftp'
   AND COALESCE(TRIM(host_key), '') = '';
