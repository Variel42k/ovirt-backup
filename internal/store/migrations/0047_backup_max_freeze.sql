-- Предел окна заморозки гостя в задании.
--
-- Пока гипервизор фиксирует точку, запись в госте стоит целиком. oVirt может
-- готовить scratch-диски минутами, а узел Kubernetes теряет лидера etcd и
-- аренды компонентов уже через десяток секунд. По истечении предела служба
-- размораживает гостя сама и понижает уровень копии до crash.
--
-- 0 — предел службы (backup.max_freeze), так существующие задания получают
-- ограничение без правки.
ALTER TABLE backup_jobs
    ADD COLUMN IF NOT EXISTS max_freeze_sec BIGINT NOT NULL DEFAULT 0
        CHECK (max_freeze_sec >= 0);
