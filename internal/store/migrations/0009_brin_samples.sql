-- Индексы по времени на таблицах метрик: B-tree -> BRIN.
--
-- health_samples, disk_samples и mount_samples растут быстрее всего во всей
-- базе: строка на объект на каждый проход монитора, то есть каждые 30 секунд.
-- За месяц это миллионы строк на установке средних размеров.
--
-- Индексы (at) на них существуют ровно для одного запроса — чистки по
-- возрасту: DELETE ... WHERE at < ?. Выборки для графиков идут не через них, а
-- через составные (server_id, ..., at DESC), которые остаются как были.
--
-- Для такой задачи B-tree — неудачный выбор. Он хранит запись на каждую строку,
-- растёт вместе с таблицей и обновляется на каждой вставке, а даёт при этом
-- ровно то, что BRIN даёт за килобайты: границы диапазонов. Данные
-- append-only, физический порядок совпадает с временным, и BRIN на такой
-- таблице описывает её несколькими сотнями байт вместо десятков мегабайт.
--
-- Чем платим: BRIN бесполезен для точечного поиска по at. Таких запросов нет —
-- точечные идут по составным индексам, а этим нужен диапазон.
--
-- pages_per_range оставлен по умолчанию (128): подбирать его имеет смысл, когда
-- есть чем измерить, а не заранее.

DROP INDEX IF EXISTS idx_health_at;
CREATE INDEX idx_health_at_brin ON health_samples USING brin (at);

DROP INDEX IF EXISTS idx_disk_samples_at;
CREATE INDEX idx_disk_samples_at_brin ON disk_samples USING brin (at);

DROP INDEX IF EXISTS idx_mount_samples_at;
CREATE INDEX idx_mount_samples_at_brin ON mount_samples USING brin (at);
